def _haystack(chunk: Chunk) -> str:
    return " ".join((chunk.content, chunk.caption or "", json.dumps(chunk.metadata, default=str))).casefold()


def _resolve(chunks: list[Chunk], doc: str, page: int, modality: str, terms: list[str]) -> Chunk:
    wanted = Modality(modality)
    candidates = [c for c in chunks if c.doc_id == doc and c.page == page and c.modality is wanted]
    if not candidates:
        raise ValueError(f"no {modality} chunk for {doc} page {page}")
    return max(
        candidates,
        key=lambda chunk: (sum(term.casefold() in _haystack(chunk) for term in terms), len(chunk.content)),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--processed", type=Path, default=Path("data/real_processed"))
    parser.add_argument("--output", type=Path, default=Path("data/eval/own_corpus_questions.jsonl"))
    args = parser.parse_args()
    chunks = load_processed_chunks(args.processed)
    rows: list[dict[str, object]] = []
    for spec in SPECS:
        evidence = spec["e"]
        selected = [_resolve(chunks, spec["doc"], page, modality, terms) for page, modality, terms in evidence]
        rows.append(
            {
                "id": spec["id"],
                "question": spec["q"],
                "reference_answer": spec["a"],
                "gold_document": spec["doc"],
                "gold_pages": sorted({chunk.page for chunk in selected}),
                "gold_modalities": sorted({chunk.modality.value for chunk in selected}),
                "gold_chunk_ids": [chunk.chunk_id for chunk in selected],
                "type": spec["type"],
                "author": "OpenAI Codex - source-grounded draft",
                "reviewer": "PENDING INDEPENDENT HUMAN REVIEW",
                "verified": False,
                "units": spec["units"],
                "fiscal_period": spec["period"],
            }
        )
    counts = Counter(str(row["type"]) for row in rows)
    if len(rows) != 60 or any(counts[kind] < 12 for kind in ("text", "table", "figure", "multimodal")):
        raise ValueError(f"invalid question balance: total={len(rows)}, counts={dict(counts)}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), encoding="utf-8")
    print(f"wrote={len(rows)} counts={dict(sorted(counts.items()))} output={args.output}")


if __name__ == "__main__":
    main()
